import { Song } from '../types/music';
import { parseSimpleNotation } from '../utils/noteParser';

function makeInterSong(
  id: string,
  title: string,
  subTitle: string,
  description: string,
  tempoBpm: number,
  timeSignature: '4/4' | '3/4' | '2/4' | '6/8',
  recommendedHandHint: string,
  tags: string[],
  rawNotation: string
): Song {
  return {
    id,
    title,
    subTitle,
    level: 'intermediate',
    levelLabel: '중급',
    description,
    estimatedMinutes: 4,
    timeSignature,
    tempoBpm,
    recommendedHandHint,
    tags,
    rawNotation,
    notes: parseSimpleNotation(rawNotation),
  };
}

