import { Song } from '../types/music';
import { parseSimpleNotation } from '../utils/noteParser';

function makeAdvancedSong(
  id: string,
  title: string,
  subTitle: string,
  description: string,
  tempoBpm: number,
  timeSignature: '4/4' | '3/4' | '2/4' | '6/8',
  recommendedHandHint: string,
  tags: string[],
  rawNotation: string,
  composer?: string
): Song {
  const notes = parseSimpleNotation(rawNotation);
  const playableNoteCount = notes.filter((n) => !n.isRest && n.pitch !== 'REST').length;

  return {
    id,
    title,
    subTitle,
    level: 'advanced',
    levelLabel: '고급',
    description,
    estimatedMinutes: 5,
    timeSignature,
    tempoBpm,
    recommendedHandHint,
    tags,
    rawNotation,
    notes,
    composer,
    playableNoteCount,
    verificationStatus: 'ARRANGEMENT_VERIFIED',
    isArranged: true,
  };
}

